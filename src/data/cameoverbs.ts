/** Look up the full fine-grained CAMEO verb for a code, with fallback */
export function getVerb(code: string): string {
  return cameoVerbs.get(code) || cameoVerbs.get(code.slice(0, 3)) || `act involving code ${code}`;
}

/** Return the broad (root) CAMEO verb for a code (present tense).
 *  For example, code "173" → "coerced" (root code "170"). */
export function getRootVerb(code: string): string {
  if (code.length === 4) {
    const root = code.slice(0, 2) + '0';
    return cameoVerbs.get(root) || `act involving code ${root}`;
  }
  return cameoVerbs.get(code) || `act involving code ${code}`;
}

